class Article {
  final String id;
  final String title;
  final String description;
  final String category;
  final String date;
  final String readTime;
  final String content;

  Article({
    required this.id,
    required this.title,
    required this.description,
    required this.category,
    required this.date,
    required this.readTime,
    required this.content,
  });
}
